// Token Radar — the value model (radar-2).
//
// One sealed snapshot in, one ranked board out. The board ranks every protocol
// that records no token and is not a wrapped, staked or bridged product of a
// token that already trades: the snapshot's watchlist is the floor, and the
// radar adds every pre-token protocol below the floor that passes the same
// filter, so the board is the whole field, not just the biggest names.
//
// Implied value is computed from the snapshot's own figures only, in four
// steps that the dashboard shows for every row:
//
//   1. Category comp. A protocol is worth what live-token protocols in its
//      own category trade at: the median market-cap-to-TVL ratio of the
//      live-token protocols in the same category (at least 3 comps, else the
//      median across all live-token protocols), clamped to [0.05, 1.5].
//      base = tvl_usd x category_multiple
//   2. Momentum. Seven-day TVL growth, clamped to [-50, +100] per cent:
//      growth_mult = 1 + clamped_growth / 100 x 0.6
//   3. Maturity. How long the protocol has run with no token, from the day
//      DefiLlama began tracking it: maturity = 0.7 + min(age, 1095) / 1095 x 0.3.
//      A protocol with no listing date is scored as 365 days old.
//   4. Reach. A protocol live on more chains reaches more farmers:
//      breadth = 1 + min(chains - 1, 5) x 0.04
//
//   implied = max(1, round(base x growth_mult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row,
// and the dashboard recomputes each row from the same figures, so the page
// and board.json always agree. Live-token protocols are kept apart and shown
// with their market caps, never mixed into the ranking.

/** One protocol as the sealed snapshot records it: exactly its ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

